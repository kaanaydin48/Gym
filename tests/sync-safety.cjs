const assert=require('node:assert/strict');
const {boot,client,setRemote,setFail}=require('./sync-harness.cjs');
(async()=>{
 const a=boot();await a.ctx.gymReady;await a.run('saveAll()');
 const original=client.rpc;let release;
 client.rpc=async(...args)=>{await new Promise(r=>release=r);return original(...args)};
 a.run("state.profile.goal='first edit';save()");
 const sending=a.run('saveAll()');
 a.run("state.profile.goal='new edit during request';save()");
 release();await sending;client.rpc=original;
 assert.equal(JSON.parse(a.storage.get('gym-tracker-pro-v1:audit-user:sync')).pending,true,'in-flight edits must remain durable pending work');
 const b=boot(a.storage);await b.ctx.gymReady;
 assert.equal(b.run('state.profile.goal'),'new edit during request','reload must preserve in-flight edits');
 console.log('PASS: edits during upload survive acknowledgement and reload');
 // A successful cloud load must refresh the device copy for the next offline boot.
 const fresh=boot();await fresh.ctx.gymReady;
 assert.equal(JSON.parse(fresh.storage.get('gym-tracker-pro-v1:audit-user')).profile.goal,'first edit');
 console.log('PASS: cloud hydration persists an offline device copy');
 fresh.run("state.profile.goal='offline pending';save()");setFail(true);
 const offline=boot(fresh.storage);await offline.ctx.gymReady;
 assert.equal(offline.run('dirty'),true,'offline reload must display pending work');
 setFail(false);await offline.events.online();
 assert.equal(offline.run('cloudReconcile'),false,'unchanged remote revision needs no manual conflict');
 assert.equal(await offline.run('saveAll()'),true);
 const verify=boot();await verify.ctx.gymReady;
 assert.equal(verify.run('state.profile.goal'),'offline pending');
 console.log('PASS: offline reload preserves pending status and reconnect retries safely');
 const other=boot();await other.ctx.gymReady;
 verify.run("state.profile.goal='device A';save()");await verify.run('saveAll()');
 other.run("state.profile.goal='device B';save()");
 assert.equal(await other.run('saveAll()'),false);
 assert.equal(other.run('cloudReady'),false,'conflicts stop automatic retry storms');
 const conflicted=boot(other.storage);await conflicted.ctx.gymReady;
 assert.equal(conflicted.run('cloudReconcile'),true);
 assert.equal(conflicted.run('state.profile.goal'),'device B');
 assert.equal(await conflicted.run('saveAll()'),false);
 console.log('PASS: stale devices preserve local edits and block cloud overwrite');
 conflicted.run("state.profile.goal='still conflicted';save()");
 const conflictReload=boot(conflicted.storage);await conflictReload.ctx.gymReady;
 assert.equal(conflictReload.run('cloudReconcile'),true,'editing a conflict must not adopt the remote base revision');
 conflicted.run('mergeBackup()');assert.equal(await conflicted.run('saveAll()'),true);
 console.log('PASS: explicit reconciliation unlocks a revision-checked save');
 const oldSet=verify.ctx.localStorage.setItem;
 verify.ctx.localStorage.setItem=()=>{throw Error('Quota exceeded')};
 verify.run("state.profile.goal='quota edit'");assert.equal(verify.run('save()'),false);
 assert.equal(await verify.run('saveAll()'),false);assert.equal(verify.run('dirty'),true);
 verify.ctx.localStorage.setItem=oldSet;
 console.log('PASS: storage failure never reports successful persistence');
})().catch(e=>{console.error(e);process.exitCode=1});
